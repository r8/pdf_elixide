enum Widths {
    Table(&'static [u16; 224]),
    Fixed(u16),
}

pub struct Base14 {
    pub name: &'static str,
    widths: Widths,
    bounds: &'static [i16; 896],
    pub ascent: f64,
    pub descent: f64,
}

impl Base14 {
    // `None` for a character the writer cannot draw in this font: one outside
    // WinAnsiEncoding, a control code, or a code naming no glyph.
    pub fn width(&self, c: char) -> Option<u16> {
        let code = unicode_to_winansi(u32::from(c))?;
        let index = usize::from(code.checked_sub(32)?);
        let width = match self.widths {
            Widths::Table(table) => table[index],
            Widths::Fixed(width) => width,
        };
        // Courier's fixed width must not cover the codes the tables leave empty.
        (HELVETICA[index] != 0).then_some(width)
    }

    // `None` for a glyph that draws nothing, or one `width` refuses.
    pub fn bounds(&self, c: char) -> Option<[f64; 4]> {
        let code = unicode_to_winansi(u32::from(c))?;
        let start = 4 * usize::from(code.checked_sub(32)?);
        let bounds: [i16; 4] = self.bounds[start..start + 4].try_into().ok()?;
        (bounds != [0; 4]).then(|| bounds.map(f64::from))
    }
}

